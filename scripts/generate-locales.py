"""Generate Android catalogs from localization/messages.json; no network dependencies."""
import json
from pathlib import Path
from xml.sax.saxutils import escape
root = Path(__file__).resolve().parents[1]
rows = json.loads((root/'localization/messages.json').read_text(encoding='utf-8'))
assert len({r['source'] for r in rows}) == len(rows), 'duplicate translation source'
def quoted(s):
    return '"'+escape(s.replace('\\','\\\\').replace('"','\\"').replace("'","\\'").replace('\n','\\n'))+'"'
for folder,lang,label in [('values','en','TideCard'),('values-zh','source','潮汐改卡'),('values-b+zh+Hant','zh-Hant','潮汐改卡')]:
    content=['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by scripts/generate-locales.py. Edit localization/messages.json. -->','<resources>',f'    <string name="app_name">{label}</string>']
    if folder=='values':
        content.append('    <string-array name="message_sources" translatable="false">')
        content.extend('        <item>'+quoted(r['source'])+'</item>' for r in rows)
        content.append('    </string-array>')
    content.append('    <string-array name="message_translations">')
    for r in rows:
        assert r[lang], ('missing translation',r['source'],lang)
        content.append('        <item>'+quoted(r[lang])+'</item>')
    content += ['    </string-array>','</resources>','']
    output=root/'app/src/main/res'/folder/'strings.xml'
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text('\n'.join(content),encoding='utf-8')
print(f'Generated {len(rows)} messages for English, Simplified Chinese and Traditional Chinese.')
